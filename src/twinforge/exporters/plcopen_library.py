def _through_references(body: str) -> str:
    """The drum body, writing each control bit through its reference."""
    return re.sub(r"^    (B(\d+)) := (.*);$",
                  r"    IF __ISVALIDREF(ref\1) THEN\n        ref\1 := \3;\n    END_IF;", body, flags=re.MULTILINE)


